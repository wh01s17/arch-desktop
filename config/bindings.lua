local function send_shortcut(mods, key)
  return function()
    hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "down" }))
    hl.timer(function()
      hl.dispatch(hl.dsp.send_key_state({ mods = mods, key = key, state = "up" }))
    end, { timeout = 50, type = "oneshot" })
  end
end
local function clipboard_shortcut(default_mods, default_key, terminal_mods, terminal_key)
  return function()
    local window = hl.get_active_window()
    local class = window and (window.class or ""):lower() or ""
    if class == "kitty" then
      send_shortcut(terminal_mods, terminal_key)()
    else
      send_shortcut(default_mods, default_key)()
    end
  end
end
